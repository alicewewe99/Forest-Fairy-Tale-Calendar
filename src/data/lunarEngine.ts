// Standard Chinese Lunar Calendar Hex Data (1900 - 2100 standard format)
// Hex bits format:
// bits 0-3: Leap month (0 if none)
// bits 4-15: 12 months length (1=30 days, 0=29 days)
// bit 16: Leap month length if any (1=30, 0=29)
